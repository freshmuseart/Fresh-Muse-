/**
 * Fresh Muse — static production build.
 *
 *   1. `vite build`  → bundled client JS/CSS + fonts into dist/assets/
 *   2. renders every route from the React page components into dist/
 *      (directory format: /about/ → dist/about/index.html)
 *   3. writes robots.txt and the sitemap pair, matching the deployed
 *      SITE_URL / BASE_PATH exactly.
 *
 * Environment:
 *   SITE_URL  production origin — defaults to https://freshmuse.freebuff.app
 *   BASE_PATH e.g. / or /Fresh-Muse-/ (set by the GitHub Pages workflow)
 */
import { build as viteBuild } from 'vite';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundleRenderer } from './render-bundle.mjs';

const ROOT = path.dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const DIST = path.join(ROOT, 'dist');

const base = process.env.BASE_PATH ?? '/';
const site = process.env.SITE_URL ?? 'https://freshmuse.freebuff.app';
const baseWithSlash = base.endsWith('/') ? base : `${base}/`;

console.log(`▶ vite build  (base: ${baseWithSlash})`);
await viteBuild({ logLevel: 'info' });

const manifest = JSON.parse(await readFile(path.join(DIST, '.vite/manifest.json'), 'utf8'));
const entry =
  manifest['src/entrypoints/client.tsx'] ??
  Object.values(manifest).find((m) => m.isEntry && m.src === 'index.html');
if (!entry) throw new Error('Client entry missing from the Vite manifest.');
const assets = {
  css: (entry.css ?? []).map((c) => `${baseWithSlash}${c}`),
  js: `${baseWithSlash}${entry.file}`,
};

console.log('▶ prerender routes');
const renderer = await bundleRenderer({ base });
const routes = renderer.listRoutes();

for (const route of routes) {
  const html = renderer.renderRoute(route, { dev: false, assets });
  const out =
    route === '/'
      ? path.join(DIST, 'index.html')
      : route === '/404/'
        ? path.join(DIST, '404.html')
        : path.join(DIST, ...route.replace(/^\/|\/$/g, '').split('/'), 'index.html');
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, html);
}
console.log(`  ${routes.length} pages`);

// --- robots.txt + sitemaps --------------------------------------------------
// The Command Center is a studio tool, not public site content.
const sitemapRoutes = routes.filter((r) => r !== '/404/' && r !== '/command-center/');
const absolute = (route) => new URL(`${baseWithSlash.replace(/\/$/, '')}${route}`, site).href;

const robots = [
  'User-agent: *',
  'Allow: /',
  'Disallow: /admin/', // editorial dashboard — noindex, not public content
  '',
  `Sitemap: ${absolute('/sitemap-index.xml')}`,
  '',
  '# generated by the Fresh Muse static build',
  '',
].join('\n');
await writeFile(path.join(DIST, 'robots.txt'), robots);

const NS =
  'xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" ' +
  'xmlns:news="http://www.google.com/schemas/sitemap-news/0.9" ' +
  'xmlns:xhtml="http://www.w3.org/1999/xhtml" ' +
  'xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" ' +
  'xmlns:video="http://www.google.com/schemas/sitemap-video/1.1"';

const urls = sitemapRoutes
  .slice()
  .sort() // the previous sitemap listed URLs alphabetically
  .map((route) => `<url><loc>${absolute(route)}</loc></url>`)
  .join('');
await writeFile(path.join(DIST, 'sitemap-0.xml'), `<?xml version="1.0" encoding="UTF-8"?><urlset ${NS}>${urls}</urlset>`);

const indexNs = 'xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"';
await writeFile(
  path.join(DIST, 'sitemap-index.xml'),
  `<?xml version="1.0" encoding="UTF-8"?><sitemapindex ${indexNs}><sitemap><loc>${absolute('/sitemap-0.xml')}</loc></sitemap></sitemapindex>`,
);

console.log(`✔ dist/ ready — ${routes.length} pages, ${sitemapRoutes.length} in sitemap`);

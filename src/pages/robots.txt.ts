/**
 * robots.txt generated per-build so the Sitemap URL always matches
 * the site + base path actually being deployed (project sub-path or domain).
 */
import type { APIRoute } from 'astro';

export const GET: APIRoute = ({ site, generator }) => {
  const base = (import.meta.env.BASE_URL ?? '/').replace(/\/$/, '');
  const sitemapUrl = new URL(`${base}/sitemap-index.xml`, site).href;
  const body = [
    'User-agent: *',
    'Allow: /',
    '',
    `Sitemap: ${sitemapUrl}`,
    '',
    `# generated by ${generator ?? 'astro'}`,
    '',
  ].join('\n');

  return new Response(body, {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
};
